const parseFullHiLoIndices = (): FullHiLoDeviation[] => {
  const entries: FullHiLoDeviation[] = [];
  for (const line of RAW_HI_LO_INDICES.trim().split("\n")) {
    const values = line.trim().split(/\s+/).map(Number);
    if (values.length < 7 || values.some(Number.isNaN)) continue;
    const [total, dealer, doubleFlag, splitFlag, surrenderFlag, initialAction] = values;
    let previousAction = ACTIONS[initialAction];
    if (!previousAction) continue;
    for (let cursor = 6; cursor + 1 < values.length; cursor += 2) {
      const index = values[cursor];
      if (index >= 1000) break;
      const nextAction = ACTIONS[values[cursor + 1]];
      if (!nextAction) break;
      const hand = handLabel(total, splitFlag === 1);
      const dealerCard = dealerLabel(dealer);
      const key = `${hand}|${dealerCard}|${index}`;
      entries.push({
        id: `${total}-${dealer}-${doubleFlag}-${splitFlag}-${surrenderFlag}-${index}-${entries.length}`,
        hand,
        dealer: dealerCard,
        index,
        normalAction: previousAction,
        deviationAction: nextAction,
        direction: "atOrAbove",
        doubleAllowed: doubleFlag === 1,
        splitAllowed: splitFlag === 1,
        surrenderAllowed: surrenderFlag === 1,
        groups: I18_KEYS.has(key) ? ["i18"] : [],
      });
      previousAction = nextAction;
    }
  }
  return entries;
};

