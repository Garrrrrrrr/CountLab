const ACTIONS: Record<number, DeviationAction> = {
  1: "S",
  2: "H",
  3: "D",
  4: "P",
  5: "R",
};

const dealerLabel = (value: number) => (value === 1 ? "A" : String(value));
const handLabel = (total: number, splitAllowed: boolean) => {
  if (total < 0) return `Soft ${Math.abs(total)}`;
  if (splitAllowed && total >= 4 && total <= 20 && total % 2 === 0) {
    const rank = total / 2;
    return rank === 10 ? "10,10" : `${rank},${rank}`;
  }
  return String(total);
};

